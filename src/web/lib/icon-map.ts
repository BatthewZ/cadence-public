/**
 * Resolves a curated icon name to its lucide-react component.
 * Returns null for unknown or empty names so callers can render a fallback.
 */
export function getIconComponent(name: string | null | undefined): LucideIcon | null {
  if (!name) return null;
  return ICON_MAP[name] ?? null;
}
